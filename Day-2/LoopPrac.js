//1️⃣ for Loop (fixed number of times)
for (let i = 1; i <= 5; i++) {
  console.log(i * i);
}


//Example 2: Count from 10 to 1
for (let i = 10; i >= 1; i--) {
  console.log(i);
}
//2️⃣ while Loop (condition-based)
//Example 1: Keep dividing by 2 until number becomes 1
let num = 16;

while (num > 1) {
  console.log(num);
  num = num / 2;
}
//Example 2: Countdown from 7
let i = 7;

while (i >= 1) {
  console.log(i);
  i--;
}
